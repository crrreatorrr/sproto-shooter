function mirror(parts) {
  return parts.map((p) => {
    const q = { ...p, id: p.id.replaceAll('BW-', 'BE-') };
    if (p.at) q.at = [260 - p.at[0], p.at[1], p.at[2]];
    if (p.size) q.size = p.size.slice();
    return q;
  });
}

